// Writes docs/design/frozen/generated.js (plan session 2B), the two things the frozen pages can't work out from
// file:// on their own:
//   icons:  the drawing of every lucide icon and Emmet glyph the frozen scripts name, from lucide-react (the package
//           4A imports, so the design and the app name the same icons) and apps/desktop/src/assets/glyphs/.
//   tokens: each component's tokens, from its "@component <id>" section in components.css, which each screen's Uses
//           list reads.
// Usage: node scripts/design-frozen.mjs [out-file]  (tests write to a temp file and compare)
import { readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, relative } from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = join(import.meta.dirname, "..");
const FROZEN = join(ROOT, "docs/design/frozen");
const GLYPHS = join(ROOT, "apps/desktop/src/assets/glyphs");
const OUT = join(FROZEN, "generated.js");
const lucide = createRequire(join(ROOT, "apps/desktop/package.json")).resolve("lucide-react/package.json");
const LUCIDE = join(lucide, "..");

/** Each component's tokens, in the order they first appear in its section. */
export function componentTokens(css) {
  const out = {};
  const parts = css.split(/\/\* @component ([a-z-]+)/).slice(1);
  for (let i = 0; i < parts.length; i += 2) {
    const id = parts[i];
    if (out[id]) throw new Error(`components.css: @component ${id} appears twice`);
    out[id] = [...new Set([...parts[i + 1].matchAll(/var\((--[a-z0-9-]+)/g)].map((m) => m[1]))];
  }
  return out;
}

/** An icon's inner SVG from lucide-react's icon data ([tag, attrs] pairs). */
const draw = (node) => node.map(([tag, a]) => `<${tag} ${Object.entries(a).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ")}/>`).join("");

export async function generate() {
  const glyphs = Object.fromEntries(readdirSync(GLYPHS).filter((f) => f.endsWith(".svg")).sort().map((f) => {
    const svg = readFileSync(join(GLYPHS, f), "utf8");
    return [f.slice(0, -4), svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"))];
  }));
  // Every quoted name in the frozen scripts that is a lucide icon or a glyph: a few extra icons cost nothing, and a
  // missing one shows as a gap that the audit reports.
  const scripts = readdirSync(FROZEN).filter((f) => f.endsWith(".js") && f !== "generated.js").sort();
  const named = new Set(scripts.flatMap((f) => [...readFileSync(join(FROZEN, f), "utf8").matchAll(/"([a-z][a-z0-9-]*)"/g)].map((m) => m[1])));
  // An old name lucide keeps as an alias (history, now rotate-ccw-clock) has no drawing of its own and is left out:
  // the design names each icon as 4A imports it, by its current name, and the audit reports one that's missing.
  const icons = {};
  for (const name of [...named].sort()) {
    const file = join(LUCIDE, "dist/esm/icons", `${name}.mjs`);
    let data = null;
    try { data = (await import(pathToFileURL(file).href)).__iconData; } catch { /* not a lucide icon */ }
    if (data && glyphs[name]) throw new Error(`glyph ${name} has the same name as a lucide icon`);
    if (data) icons[name] = draw(data.node);
    else if (glyphs[name]) icons[name] = glyphs[name];
  }
  const tokens = componentTokens(readFileSync(join(FROZEN, "components.css"), "utf8"));
  const version = JSON.parse(readFileSync(join(LUCIDE, "package.json"), "utf8")).version;
  return `// SPDX-License-Identifier: AGPL-3.0-or-later AND ISC AND MIT
// Generated by scripts/design-frozen.mjs; run it again after changing components.css, an icon name in the frozen
// scripts, or a glyph. Don't edit by hand.
// The icons named below that aren't Emmet glyphs are from lucide-react ${version}: ISC License, Copyright (c) 2026
// Lucide Icons and Contributors; those derived from Feather are MIT, Copyright (c) 2013-present Cole Bemis. Permission
// to use, copy, modify, and/or distribute them is granted provided the copyright notice and permission notice appear
// in all copies (apps/desktop/node_modules/lucide-react/LICENSE has the full text).
window.EMMET_GEN = ${JSON.stringify({ lucide: version, glyphs: Object.keys(glyphs), icons, tokens }, null, 1)};
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) {
  const out = process.argv[2] ?? OUT;
  const text = await generate();
  writeFileSync(out, text);
  const g = JSON.parse(text.slice(text.indexOf("{"), text.lastIndexOf("}") + 1));
  console.log(`design-frozen: ${Object.keys(g.icons).length} icons, ${Object.keys(g.tokens).length} components → ${relative(ROOT, out)}`);
}
